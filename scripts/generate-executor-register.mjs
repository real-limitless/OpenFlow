#!/usr/bin/env node
/**
 * Generates src/lib/engine/executors/register-builtins.ts from
 * BUILTIN_EXECUTOR_MODULES so Nitro/Rolldown production builds keep every
 * executor (import.meta.glob side-effects get tree-shaken).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const outPath = join(root, "src/lib/engine/executors/register-builtins.ts");
const runtimePath = join(root, "src/lib/engine/node-runtime.ts");

/**
 * Parse BUILTIN_EXECUTOR_MODULES from source without executing TS.
 * Entries are plain object literals: { type, modulePath, exportName }.
 */
export function loadModules() {
  const src = readFileSync(runtimePath, "utf8");
  const start = src.indexOf("export const BUILTIN_EXECUTOR_MODULES");
  if (start < 0) throw new Error("BUILTIN_EXECUTOR_MODULES not found");
  const arrStart = src.indexOf("[", start);
  if (arrStart < 0) throw new Error("array start not found");

  // Bracket-match the top-level array.
  let depth = 0;
  let end = -1;
  for (let i = arrStart; i < src.length; i++) {
    const ch = src[i];
    if (ch === "[") depth++;
    else if (ch === "]") {
      depth--;
      if (depth === 0) {
        end = i;
        break;
      }
    }
  }
  if (end < 0) throw new Error("array end not found");
  const body = src.slice(arrStart, end + 1);

  const modules = [];

  // Split the array into its top-level `{...}` entries with a depth-aware scan.
  //
  // A regex cannot do this. An entry may contain a nested object (e.g. the
  // `unavailable: { setter, reason }` tag), and an innermost-brace pattern like
  // /\{([^{}]+)\}/g matches that inner object first -- it has no type/modulePath
  // /exportName, so it is skipped, and the enclosing entry is then never matched.
  // The executor silently vanishes from the generated file while the build stays
  // green. Track string literals too, so braces inside a reason string are inert.
  let braceDepth = 0;
  let entryStart = -1;
  let quote = null;
  for (let i = 0; i < body.length; i++) {
    const ch = body[i];
    if (quote) {
      if (ch === "\\") i++;
      else if (ch === quote) quote = null;
      continue;
    }
    if (ch === '"' || ch === "'" || ch === "`") {
      quote = ch;
      continue;
    }
    if (ch === "{") {
      if (braceDepth === 0) entryStart = i;
      braceDepth++;
    } else if (ch === "}") {
      braceDepth--;
      if (braceDepth === 0 && entryStart >= 0) {
        const block = body.slice(entryStart, i + 1);
        const type = /type:\s*"([^"]+)"/.exec(block)?.[1];
        const modulePath = /modulePath:\s*"([^"]+)"/.exec(block)?.[1];
        const exportName = /exportName:\s*"([^"]+)"/.exec(block)?.[1];
        if (type && modulePath && exportName) {
          modules.push({ type, modulePath, exportName });
        }
        entryStart = -1;
      }
    }
  }

  if (modules.length === 0) {
    throw new Error("Parsed 0 executor modules from node-runtime.ts");
  }

  // Every entry declares exactly one modulePath, so this count is the ground
  // truth for how many entries the manifest holds. Turns any future parse gap
  // into a build failure instead of a silently under-populated registry.
  const expected = (body.match(/\bmodulePath:/g) ?? []).length;
  if (modules.length !== expected) {
    throw new Error(
      `Parsed ${modules.length} executor modules but the manifest declares ${expected} ` +
        `modulePath entries. The BUILTIN_EXECUTOR_MODULES parser is out of date.`,
    );
  }
  return modules;
}

/** Render the full contents of register-builtins.ts for a parsed manifest. */
export function renderRegister(modules) {
  const lines = [
    "// AUTO-GENERATED by scripts/generate-executor-register.mjs — do not edit by hand.",
    "// Source of truth: BUILTIN_EXECUTOR_MODULES in node-runtime.ts",
    'import { registerExecutor, markExecutorsSeeded } from "../node-runtime";',
    'import type { NodeExecutor } from "../types";',
    "",
  ];

  const registers = [];
  for (const [i, e] of modules.entries()) {
    const rel = e.modulePath.replace(/^\.\/executors\//, "./");
    const alias = `exec_${i}`;
    lines.push(`import { ${e.exportName} as ${alias} } from "${rel}";`);
    registers.push(
      `  registerExecutor(${JSON.stringify(e.type)}, ${alias} as NodeExecutor);`,
    );
  }

  lines.push("");
  lines.push(
    "/** Register every builtin executor via static imports (Nitro-safe). Idempotent. */",
  );
  lines.push("export function seedBuiltinExecutors(): void {");
  lines.push(...registers);
  lines.push("  markExecutorsSeeded();");
  lines.push("}");
  lines.push("");
  lines.push("// Eager side-effect so importing this module always populates the registry.");
  lines.push("seedBuiltinExecutors();");
  lines.push("");

  return lines.join("\n");
}

// Only write when run as a CLI. Importing this module (the freshness test does)
// must stay side-effect free, or the test would regenerate the very file it checks.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const modules = loadModules();
  writeFileSync(outPath, renderRegister(modules));
  console.log(`Wrote ${modules.length} executors → ${outPath}`);
}
